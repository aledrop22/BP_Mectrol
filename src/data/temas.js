export function obterVariaveisTema(paletaId, modo) {
  const paleta =
    PALETAS_TEMAS.find((p) => p.id === paletaId) || PALETAS_TEMAS[0];
  const modoEfetivo =
    modo === 'light' || modo === 'dark' ? modo : paleta.modoPadrao;
  const cores = paleta.modes[modoEfetivo];

  return {
    paleta,
    modoEfetivo,
    estiloCards: paleta.estiloCards || 'colorido',
    cores,
    cssVars: {
      '--bg-canvas': cores.bgCanvas,
      '--bg-surface': cores.bgSurface,
      '--bg-elevated': cores.bgElevated,
      '--bg-subtle': cores.bgSubtle,
      '--border-subtle': cores.borderSubtle,
      '--border-strong': cores.borderStrong,
      '--text-primary': cores.textPrimary,
      '--text-secondary': cores.textSecondary,
      '--text-muted': cores.textMuted,
      '--accent-primary': cores.accentPrimary,
      '--accent-hover': cores.accentHover,
      '--accent-soft': cores.accentSoft,
      '--accent-text': cores.accentText,
    },
  };
}
